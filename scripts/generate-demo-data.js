/**
 * Generates the JSON dataset used by the demo deployment.
 *
 * The demo runs without MongoDB: `src/database.js` reads these files instead.
 * Product images already live in `images/products/`, named by the product id,
 * so this script discovers the ids from the filesystem and builds a catalogue
 * around them.
 *
 * Usage:  node scripts/generate-demo-data.js
 *
 * Product names, prices and descriptions are generated sample data — the
 * original catalogue is not part of this repository.
 */

const fs = require('fs');
const path = require('path');
const bcryptjs = require('bcryptjs');

const ROOT = path.join(__dirname, '..');
const IMAGES_DIR = path.join(ROOT, 'images', 'products');
const OUT_DIR = path.join(ROOT, 'src', 'data');
const CONFIG = require(path.join(ROOT, 'src', 'config', 'config.json'));

/* ------------------------------------------------------------------ *
 * Deterministic RNG so re-running the script produces the same output
 * ------------------------------------------------------------------ */
let seed = 20260908;
const rand = () => {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
};
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const between = (min, max) => min + Math.floor(rand() * (max - min + 1));

/* ------------------------------------------------------------------ *
 * Catalogue vocabulary, per category
 * ------------------------------------------------------------------ */
const CATALOGUE = {
  wearables: {
    prefix: ['Everyday', 'Weekend', 'Studio', 'Field', 'Court', 'Trail', 'City', 'Classic'],
    noun: ['Hoodie', 'Sneakers', 'Windbreaker', 'Tee', 'Cap', 'Tote Bag', 'Jacket', 'Joggers'],
    price: [590, 2890],
    options: () => ({
      Size: ['S', 'M', 'L', 'XL'],
      Color: pick([['Black', 'Off White'], ['Charcoal', 'Sand', 'Navy'], ['Black']]),
    }),
    short: 'Made for daily wear, built to survive the laundry pile.',
  },
  collectibles: {
    prefix: ['Series One', 'Limited', 'Holo', 'Rookie', 'Vintage', 'Signature', 'Anniversary', 'Chrome'],
    noun: ['Card Pack', 'Vinyl Figure', 'Enamel Pin Set', 'Sticker Sheet', 'Trading Card Box', 'Keychain', 'Diorama Kit', 'Badge Set'],
    price: [250, 4500],
    options: () => pick([{ Edition: ['Standard', 'Foil'] }, {}, { Variant: ['A', 'B'] }]),
    short: 'Small run, numbered, and not coming back once it is gone.',
  },
  'art-books': {
    prefix: ['Notes on', 'Studies in', 'Field Guide to', 'The Book of', 'Sketches of', 'A Year of', 'Fragments of', 'Atlas of'],
    noun: ['Colour', 'Quiet Places', 'Type', 'Street Light', 'Still Life', 'Paper', 'Shadow', 'Everyday Objects'],
    price: [450, 1950],
    options: () => pick([{ Cover: ['Softcover', 'Hardcover'] }, {}]),
    short: 'Printed in a small run on uncoated stock, 120 pages.',
  },
  'digital-products': {
    prefix: ['Grain', 'Halftone', 'Golden Hour', 'Night Market', 'Monochrome', 'Soft Focus', 'Analog', 'Overcast'],
    noun: ['Preset Pack', 'Icon Set', 'Brush Kit', 'Font Family', 'LUT Collection', 'Texture Pack', 'Template Set', 'Sound Pack'],
    price: [150, 1290],
    options: () => pick([{ License: ['Personal', 'Commercial'] }, {}]),
    short: 'Instant download. Works with the usual desktop apps.',
  },
};

const FULL_DETAIL = [
  'This is sample data created for the public demo. The product photography is stock imagery and the description below is filler text written to give the page a realistic amount of content.',
  'Every item in this demo store is generated by scripts/generate-demo-data.js. Names, prices and copy are invented; the original catalogue lived in a database that is no longer part of this project.',
  'Shipping, stock levels and payment are not implemented in this demo. Browsing, filtering, product detail and reviews all run against the real Express API.',
];

/* ------------------------------------------------------------------ *
 * Build
 * ------------------------------------------------------------------ */
const slugify = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/**
 * The accounts behind the "explore as" buttons on the login page. The handles,
 * the `<handle>@bbad.com` address and the shared password are all fixed by
 * `onClikcloginDemo` in the frontend, so they cannot be renamed here alone.
 *
 * Ids must be 24-character hex strings: parts of the codebase wrap user ids in
 * `new ObjectId(...)`, which rejects anything else.
 */
const DEMO_PASSWORD = '12341234';

// bcrypt salts are random, which would make every run produce a different
// Users.json and leave the committed dataset permanently "out of date". These
// are demo accounts with a published password, so a fixed salt costs nothing
// and keeps the generator's output reproducible.
const DEMO_PASSWORD_SALT = '$2a$10$yYeh83SuBCycrb9yC/kHxe';
const DEMO_USERS = [
  { handle: 'fizri', displayname: 'Fizri', rank_id: 'rank3' },
  { handle: 'burni', displayname: 'Burni', rank_id: 'rank2' },
  { handle: 'kuri', displayname: 'Kuri', rank_id: 'rank1' },
].map((user, index) => ({
  ...user,
  _id: `65000000000000000000000${index + 1}`,
  email: `${user.handle}@bbad.com`,
}));

function discoverProductIds() {
  if (!fs.existsSync(IMAGES_DIR)) {
    throw new Error(`Image directory not found: ${IMAGES_DIR}`);
  }
  const ids = new Set();
  for (const file of fs.readdirSync(IMAGES_DIR)) {
    const m = file.match(/^([0-9a-f]{24})-/);
    if (m) ids.add(m[1]);
  }
  return [...ids].sort();
}

function buildProducts(ids, categories) {
  const usedNames = new Set();

  return ids.map((id, index) => {
    const category = categories[index % categories.length];
    const spec = CATALOGUE[category._id];

    let name;
    do {
      name = `${pick(spec.prefix)} ${pick(spec.noun)}`;
    } while (usedNames.has(name));
    usedNames.add(name);

    const [minPrice, maxPrice] = spec.price;
    const price = between(minPrice / 10, maxPrice / 10) * 10;

    return {
      _id: id,
      product_name: name,
      product_url_name: slugify(name),
      category_id: category._id,
      product_price: price,
      thumb_photo: `/images/products/${id}-thumb100100.jpg`,
      card_photo: `/images/products/${id}-card400600.jpg`,
      product_photo: [1, 2, 3, 4, 5].map(
        (n) => `/images/products/${id}-800400-${n}.jpg`
      ),
      short_details: spec.short,
      full_detail: pick(FULL_DETAIL),
      option: spec.options(),
      stock: between(0, 40),
    };
  });
}

function buildReviews(products) {
  const bodies = [
    'Arrived quicker than I expected. Packaging was neat.',
    'Exactly what the photos show. No complaints.',
    'Good quality for the price, would order again.',
    'Nice piece, though smaller than I pictured it.',
    'Been using it every day for a month and it still looks new.',
    'Solid. Bought a second one as a gift.',
  ];
  const reviews = [];
  products.forEach((product, i) => {
    // At most one review per user per product: the API treats a second one as
    // an edit, and duplicates would make the "my reviews" page inconsistent.
    const authors = [...DEMO_USERS]
      .sort(() => rand() - 0.5)
      .slice(0, between(0, DEMO_USERS.length));

    authors.forEach((author, n) => {
      reviews.push({
        _id: `rev${String(i).padStart(3, '0')}${n}`,
        product_id: product._id,
        user_id: author._id,
        displayname: author.displayname,
        rating: between(3, 5),
        comment: pick(bodies),
        create_date: new Date(2026, between(0, 7), between(1, 28)).toISOString(),
      });
    });
  });
  return reviews;
}

function main() {
  const categories = CONFIG.Categories;
  const ids = discoverProductIds();

  if (ids.length === 0) {
    throw new Error('No product images found — nothing to generate.');
  }

  const products = buildProducts(ids, categories);
  const reviews = buildReviews(products);

  // Accounts for the "explore as" buttons on the login page. Account changes
  // are blocked by the demo guard in userRoutes.js.
  const passwordHash = bcryptjs.hashSync(DEMO_PASSWORD, DEMO_PASSWORD_SALT);
  const users = DEMO_USERS.map(({ handle, ...user }) => ({
    ...user,
    password: passwordHash,
    user_photo: '',
  }));

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const files = {
    'Categories.json': categories,
    'Products.json': products,
    'Reviews.json': reviews,
    'Users.json': users,
    'Orders.json': [],
  };

  for (const [file, data] of Object.entries(files)) {
    fs.writeFileSync(
      path.join(OUT_DIR, file),
      JSON.stringify(data, null, 2) + '\n'
    );
    const count = Array.isArray(data) ? data.length : 1;
    console.log(`${file.padEnd(18)} ${String(count).padStart(3)} records`);
  }

  const perCategory = categories
    .map((c) => `${c.category_name}: ${products.filter((p) => p.category_id === c._id).length}`)
    .join(' · ');
  console.log(`\n${products.length} products — ${perCategory}`);
}

main();
